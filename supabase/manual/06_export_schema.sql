--
-- Ne yapar: public şemasındaki tabloları, kolonları, kısıtları, indeksleri, RLS
-- ayarlarını, politikaları, fonksiyonları ve tetikleyicileri tek bir SQL metni
-- olarak üretir. Hiçbir şeyi değiştirmez; veri (satırlar) içermez.
-- Bu çıktı repoya "başlangıç migration'ı" olarak kaydedilecek.
--
-- Ne zaman: 01–05 betikleri çalıştırıldıktan SONRA.
-- Nasıl: SQL Editor → New query → yapıştır → Run → tek hücrelik sonucu kopyala
-- (ya da sonucu CSV olarak indir) ve Proficios/supabase/baseline-export.txt
-- dosyasına kaydet.

with
tables as (
    select c.oid, c.relname, c.relrowsecurity
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r'
),
statements as (
    -- 0. enum tipleri
    select 0::numeric as ord, t.typname::text as name,
           format('create type public.%I as enum (%s);', t.typname,
                  string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)) as stmt
      from pg_type t
      join pg_namespace n on n.oid = t.typnamespace
      join pg_enum e on e.enumtypid = t.oid
     where n.nspname = 'public'
     group by t.typname

    union all
    -- 0.5 bağımsız sekanslar (identity olmayanlar)
    select 0.5, c.relname, format('create sequence if not exists public.%I;', c.relname)
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'S'
       and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')

    union all
    -- 1. tablolar ve kolonlar
    select 1, t.relname,
           format(E'create table if not exists public.%I (\n%s\n);', t.relname,
               (select string_agg(
                        format('    %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
                        || case a.attidentity
                               when 'a' then ' generated always as identity'
                               when 'd' then ' generated by default as identity'
                               else '' end
                        || coalesce(' default ' || pg_get_expr(ad.adbin, ad.adrelid), '')
                        || case when a.attnotnull then ' not null' else '' end,
                        E',\n' order by a.attnum)
                  from pg_attribute a
                  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
                 where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
      from tables t

    union all
    -- 2. kısıtlar: önce birincil/benzersiz/check, sonra yabancı anahtarlar
    select case con.contype when 'f' then 2.5 else 2 end, t.relname || '.' || con.conname,
           format('alter table public.%I add constraint %I %s;', t.relname, con.conname,
                  pg_get_constraintdef(con.oid))
      from pg_constraint con
      join tables t on t.oid = con.conrelid
     where con.contype in ('p', 'u', 'c', 'f')

    union all
    -- 3. kısıt dışı indeksler
    select 3, i.indexname, i.indexdef || ';'
      from pg_indexes i
     where i.schemaname = 'public'
       and not exists (
           select 1 from pg_constraint con
            where con.conindid = format('%I.%I', i.schemaname, i.indexname)::regclass
       )

    union all
    -- 4. RLS açık tablolar
    select 4, t.relname, format('alter table public.%I enable row level security;', t.relname)
      from tables t
     where t.relrowsecurity

    union all
    -- 5. politikalar
    select 5, p.tablename || '.' || p.policyname,
           format('create policy %I on public.%I as %s for %s to %s%s%s;',
                  p.policyname, p.tablename, lower(p.permissive), lower(p.cmd),
                  array_to_string(p.roles, ', '),
                  coalesce(E'\n    using (' || p.qual || ')', ''),
                  coalesce(E'\n    with check (' || p.with_check || ')', ''))
      from pg_policies p
     where p.schemaname = 'public'

    union all
    -- 6. fonksiyonlar (eklentilere ait olanlar hariç)
    select 6, p.proname, pg_get_functiondef(p.oid) || ';'
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.prokind = 'f'
       and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

    union all
    -- 7. tetikleyiciler
    select 7, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
      from pg_trigger tg
      join tables t on t.oid = tg.tgrelid
     where not tg.tgisinternal

    union all
    -- 8. istemci rollerinin tablo yetkileri (bilgi amaçlı, yorum satırı olarak)
    select 8, g.table_name,
           format('-- grants on %I: %s', g.table_name,
                  string_agg(g.grantee || ':' || g.privilege_type, ', ' order by g.grantee, g.privilege_type))
      from information_schema.role_table_grants g
     where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated')
     group by g.table_name
)
select string_agg(stmt, E'\n\n' order by ord, name) as baseline_sql
  from statements;
